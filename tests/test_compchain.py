import pytest
import subprocess
import sys


def eval_expression(expr: str) -> int:
    res = subprocess.run("../nc", input=expr, text=True, capture_output=True)
    if res.stderr:
        print(res.stderr, file=sys.stderr)
    try:
        return int(res.stdout.splitlines()[-1])
    except Exception:
        raise


